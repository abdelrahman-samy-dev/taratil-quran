/**
 * The Arabic hadith books offered by hadith-api, with metadata the API does not
 * provide in Arabic. Counts follow each edition's own numbering (last hadith
 * number); sizes were measured from the jsDelivr files (gzip / decoded).
 */
export interface BookInfo {
  slug: string;
  name: string;
  /** Short name used in source lines: «رواه البخاري». */
  short: string;
  compiler: string;
  /** Hijri year of the compiler's death. */
  died?: number;
  count: number;
  /** Compressed transfer size in bytes (what the user downloads). */
  gzBytes: number;
  /** Decoded JSON size in bytes, used for the download progress bar. */
  rawBytes: number;
  group: 'six' | 'other';
  /** Second numbering carried in `arabicnumber` (Sahih Muslim). */
  altNumbering?: string;
  /** Text uses Persian forms of yeh/kaf that need converting. */
  persianLetters?: boolean;
}

