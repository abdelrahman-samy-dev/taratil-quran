const SECTION_NAMES: Record<string, string[]> = { bukhari: BUKHARI, muslim: MUSLIM };

/** «كتاب الإيمان», or null when no verified Arabic title exists. */
export function sectionTitle(slug: string, section: number): string | null {
  const name = SECTION_NAMES[slug]?.[section];
  if (!name) return null;
  return name === 'المقدمة' ? name : `كتاب ${name}`;
}
